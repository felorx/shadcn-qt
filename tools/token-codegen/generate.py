#!/usr/bin/env python3
"""Generate QSS, Python theme dict, and C++ token header from packages/design-tokens/tokens.json."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOKENS_PATH = ROOT / "packages" / "design-tokens" / "tokens.json"
OUT_PY_DIR = ROOT / "packages" / "python" / "qtshadcn" / "_generated"
OUT_CPP = ROOT / "packages" / "cpp" / "qtshadcn" / "include" / "qtshadcn" / "ThemeTokens.h"
OUT_QSS_LIGHT = OUT_PY_DIR / "base_light.qss"
OUT_QSS_DARK = OUT_PY_DIR / "base_dark.qss"


def _palette_qss(T: dict, r_md: str, r_sm: str, sans: str) -> str:
    """Single-theme QSS body (no file header)."""
    return f"""
QWidget {{
  background-color: {T["background"]};
  color: {T["foreground"]};
  font-family: {sans};
}}

QMainWindow, QDialog {{
  background-color: {T["background"]};
}}

QFrame#qtshadcn-card {{
  background-color: {T["card"]};
  color: {T["cardForeground"]};
  border: 1px solid {T["border"]};
  border-radius: {r_md};
}}

QLineEdit#qtshadcn-input, QTextEdit#qtshadcn-input, QPlainTextEdit#qtshadcn-input {{
  background-color: {T["background"]};
  color: {T["foreground"]};
  border: 1px solid {T["input"]};
  border-radius: {r_sm};
  padding: 6px 10px;
  selection-background-color: {T["primary"]};
  selection-color: {T["primaryForeground"]};
}}

QLineEdit#qtshadcn-input:focus, QTextEdit#qtshadcn-input:focus, QPlainTextEdit#qtshadcn-input:focus {{
  border: 1px solid {T["ring"]};
}}

QPushButton#qtshadcn-button {{
  border-radius: {r_sm};
  padding: 8px 16px;
  min-height: 20px;
}}

QPushButton#qtshadcn-button[qtshadcn_variant="default"] {{
  background-color: {T["primary"]};
  color: {T["primaryForeground"]};
  border: 1px solid {T["primary"]};
}}

QPushButton#qtshadcn-button[qtshadcn_variant="secondary"] {{
  background-color: {T["secondary"]};
  color: {T["secondaryForeground"]};
  border: 1px solid {T["border"]};
}}

QPushButton#qtshadcn-button[qtshadcn_variant="destructive"] {{
  background-color: {T["destructive"]};
  color: {T["destructiveForeground"]};
  border: 1px solid {T["destructive"]};
}}

QPushButton#qtshadcn-button[qtshadcn_variant="outline"] {{
  background-color: transparent;
  color: {T["foreground"]};
  border: 1px solid {T["border"]};
}}

QPushButton#qtshadcn-button[qtshadcn_variant="ghost"] {{
  background-color: transparent;
  color: {T["foreground"]};
  border: 1px solid transparent;
}}

QPushButton#qtshadcn-button[qtshadcn_variant="link"] {{
  background-color: transparent;
  color: {T["primary"]};
  border: none;
  text-decoration: underline;
}}

QPushButton#qtshadcn-button[qtshadcn_size="sm"] {{
  padding: 6px 12px;
  font-size: 12px;
}}

QPushButton#qtshadcn-button[qtshadcn_size="lg"] {{
  padding: 10px 20px;
  font-size: 15px;
}}
"""


def build_qss_pair(themes: dict, radius: dict, font: dict) -> tuple[str, str]:
    r_md = radius.get("md", "6px")
    r_sm = radius.get("sm", "4px")
    sans = font.get("sansFamily", "sans-serif")
    L, D = themes["light"], themes["dark"]
    header = "/* Generated by tools/token-codegen/generate.py — do not edit by hand */\n"
    return header + _palette_qss(L, r_md, r_sm, sans), header + _palette_qss(D, r_md, r_sm, sans)


def write_python_module(themes: dict, radius: dict, font: dict, light_qss: str, dark_qss: str) -> None:
    OUT_PY_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_PY_DIR / "__init__.py").write_text('"""Generated artifacts."""\n', encoding="utf-8")

    colors_py = OUT_PY_DIR / "colors.py"
    lines = [
        '"""Generated semantic colors — do not edit by hand."""',
        "",
        "THEMES = " + json.dumps(themes, indent=2),
        "",
        "RADIUS = " + json.dumps(radius, indent=2),
        "",
        "FONT = " + json.dumps(font, indent=2),
        "",
    ]
    colors_py.write_text("\n".join(lines), encoding="utf-8")

    def esc(s: str) -> str:
        return s.replace('"""', '\\"\\"\\"')

    qss_py = OUT_PY_DIR / "base_qss.py"
    qss_py.write_text(
        '"""Generated base QSS — do not edit by hand."""\n\n'
        f'LIGHT_QSS = """{esc(light_qss)}"""\n\n'
        f'DARK_QSS = """{esc(dark_qss)}"""\n\n'
        "BASE_QSS = LIGHT_QSS  # alias for light theme\n",
        encoding="utf-8",
    )


def write_cpp_header(themes: dict, radius: dict) -> None:
    OUT_CPP.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "#pragma once",
        "",
        "#include <QtGlobal>",
        "",
        "namespace qtshadcn {",
        "",
        "struct ThemeTokens {",
    ]
    for theme_name, palette in themes.items():
        lines.append(f"    struct {theme_name.capitalize()} {{")
        for key, val in palette.items():
            ident = "".join(p if p.isalnum() else "_" for p in key)
            lines.append(f'        static constexpr const char* k{ident} = "{val}";')
        lines.append("    };")
    lines.append("    struct Radius {")
    for key, val in radius.items():
        lines.append(f'        static constexpr const char* k{key} = "{val}";')
    lines.append("    };")
    lines.append("};")
    lines.append("")
    lines.append("} // namespace qtshadcn")
    lines.append("")
    OUT_CPP.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    if not TOKENS_PATH.is_file():
        print(f"Missing {TOKENS_PATH}", file=sys.stderr)
        return 1
    data = json.loads(TOKENS_PATH.read_text(encoding="utf-8"))
    themes = data["themes"]
    radius = data["radius"]
    font = data.get("font", {})

    light_qss, dark_qss = build_qss_pair(themes, radius, font)

    OUT_PY_DIR.mkdir(parents=True, exist_ok=True)
    OUT_QSS_LIGHT.write_text(light_qss, encoding="utf-8")
    OUT_QSS_DARK.write_text(dark_qss, encoding="utf-8")

    write_python_module(themes, radius, font, light_qss, dark_qss)
    write_cpp_header(themes, radius)
    print(
        f"Wrote {OUT_QSS_LIGHT}, {OUT_QSS_DARK}, {OUT_PY_DIR}/colors.py, base_qss.py, {OUT_CPP}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
