"""Pure-Python QSS renderer shared by built-in and user-defined themes."""

from __future__ import annotations

from typing import Mapping


def render_stylesheet(
    colors: Mapping[str, str],
    radius: Mapping[str, str],
    font: Mapping[str, str],
    *,
    designer_preview: bool = False,
) -> str:
    c = colors
    r_sm = radius.get("sm", "4px")
    r_md = radius.get("md", "6px")
    r_lg = radius.get("lg", "8px")
    sans = font.get("sansFamily", "sans-serif")
    # Qt already chooses the correct native system UI font.  Emitting CSS
    # generic families makes Qt perform a missing-font alias lookup and warn.
    font_rule = (
        "" if sans in {"sans-serif", "system-ui"} else f"  font-family: {sans};\n"
    )
    root_selector = "QWidget[qtshadcn_component]" if designer_preview else "QWidget"
    window_rules = (
        ""
        if designer_preview
        else f"QMainWindow, QDialog {{ background-color: {c['background']}; }}"
    )
    tooltip_rules = (
        ""
        if designer_preview
        else f"""QToolTip {{
  background-color: {c["popover"]}; color: {c["popoverForeground"]};
  border: 1px solid {c["border"]}; border-radius: {r_sm}; padding: 4px 8px;
}}"""
    )
    tab_bar = (
        'QTabWidget[qtshadcn_component="tabs"] QTabBar'
        if designer_preview
        else "QTabBar"
    )
    menu_rules = (
        ""
        if designer_preview
        else f"""QMenu, QListView {{ background: {c["popover"]}; color: {c["popoverForeground"]}; border: 1px solid {c["border"]}; }}
QMenu::item:selected, QListView::item:selected {{ background: {c["accent"]}; color: {c["accentForeground"]}; }}"""
    )

    return f"""/* Generated by qtshadcn -- safe to extend with extra_qss */
{root_selector} {{
  background-color: {c["background"]};
  color: {c["foreground"]};
{font_rule}}}
{window_rules}
{tooltip_rules}

QFrame[qtshadcn_component="card"], QFrame[qtshadcn_component="alert"] {{
  background-color: {c["card"]}; color: {c["cardForeground"]};
  border: 1px solid {c["border"]}; border-radius: {r_md};
}}
QFrame[qtshadcn_component="card"][elevated="true"] {{
  border: 2px solid {c["border"]};
}}
QFrame[qtshadcn_component="alert"][variant="destructive"] {{
  color: {c["destructive"]}; border-color: {c["destructive"]};
}}

QLineEdit[qtshadcn_component="input"],
QPlainTextEdit[qtshadcn_component="textarea"] {{
  background-color: {c["background"]}; color: {c["foreground"]};
  border: 1px solid {c["input"]}; border-radius: {r_sm};
  padding: 6px 10px; selection-background-color: {c["primary"]};
  selection-color: {c["primaryForeground"]};
}}
QLineEdit[qtshadcn_component="input"]:focus,
QPlainTextEdit[qtshadcn_component="textarea"]:focus {{ border-color: {c["ring"]}; }}
QLineEdit[invalid="true"], QPlainTextEdit[invalid="true"] {{ border-color: {c["destructive"]}; }}
QLineEdit[qtshadcn_component="input"]:disabled,
QPlainTextEdit[qtshadcn_component="textarea"]:disabled {{ color: {c["mutedForeground"]}; background: {c["muted"]}; }}

QPushButton[qtshadcn_component="button"] {{
  border-radius: {r_sm}; padding: 8px 16px; min-height: 20px;
}}
QPushButton[qtshadcn_component="button"][variant="default"] {{
  background-color: {c["primary"]}; color: {c["primaryForeground"]}; border: 1px solid {c["primary"]};
}}
QPushButton[qtshadcn_component="button"][variant="secondary"] {{
  background-color: {c["secondary"]}; color: {c["secondaryForeground"]}; border: 1px solid {c["border"]};
}}
QPushButton[qtshadcn_component="button"][variant="destructive"] {{
  background-color: {c["destructive"]}; color: {c["destructiveForeground"]}; border: 1px solid {c["destructive"]};
}}
QPushButton[qtshadcn_component="button"][variant="outline"] {{
  background-color: transparent; color: {c["foreground"]}; border: 1px solid {c["border"]};
}}
QPushButton[qtshadcn_component="button"][variant="ghost"] {{
  background-color: transparent; color: {c["foreground"]}; border: 1px solid transparent;
}}
QPushButton[qtshadcn_component="button"][variant="link"] {{
  background-color: transparent; color: {c["primary"]}; border: none; text-decoration: underline;
}}
QPushButton[qtshadcn_component="button"]:hover {{ border-color: {c["ring"]}; }}
QPushButton[qtshadcn_component="button"]:pressed {{ padding-top: 9px; padding-bottom: 7px; }}
QPushButton[qtshadcn_component="button"]:disabled {{
  background-color: {c["muted"]}; color: {c["mutedForeground"]}; border-color: {c["border"]};
}}
QPushButton[qtshadcn_component="button"][shadcnSize="sm"] {{ padding: 5px 12px; font-size: 12px; }}
QPushButton[qtshadcn_component="button"][shadcnSize="lg"] {{ padding: 10px 20px; font-size: 15px; }}
QPushButton[qtshadcn_component="button"][shadcnSize="icon"] {{ padding: 8px; min-width: 20px; }}

QLabel[qtshadcn_component="label"][variant="muted"] {{ color: {c["mutedForeground"]}; }}
QLabel[qtshadcn_component="label"][variant="lead"] {{ color: {c["mutedForeground"]}; font-size: 16px; }}
QLabel[qtshadcn_component="label"][variant="large"] {{ font-size: 18px; font-weight: 600; }}
QLabel[qtshadcn_component="label"][variant="small"] {{ font-size: 12px; font-weight: 600; }}
QLabel[qtshadcn_component="badge"] {{ border-radius: {r_lg}; padding: 2px 8px; font-weight: 600; }}
QLabel[qtshadcn_component="badge"][variant="default"] {{ background: {c["primary"]}; color: {c["primaryForeground"]}; }}
QLabel[qtshadcn_component="badge"][variant="secondary"] {{ background: {c["secondary"]}; color: {c["secondaryForeground"]}; }}
QLabel[qtshadcn_component="badge"][variant="outline"] {{ background: transparent; border: 1px solid {c["border"]}; }}
QLabel[qtshadcn_component="badge"][variant="destructive"] {{ background: {c["destructive"]}; color: {c["destructiveForeground"]}; }}

QCheckBox[qtshadcn_component="checkbox"], QRadioButton[qtshadcn_component="radio"] {{ spacing: 8px; }}
QCheckBox[qtshadcn_component="checkbox"]::indicator,
QRadioButton[qtshadcn_component="radio"]::indicator {{ width: 15px; height: 15px; border: 1px solid {c["input"]}; }}
QCheckBox[qtshadcn_component="checkbox"]::indicator {{ border-radius: {r_sm}; }}
QRadioButton[qtshadcn_component="radio"]::indicator {{ border-radius: 8px; }}
QCheckBox[qtshadcn_component="checkbox"]::indicator:checked,
QRadioButton[qtshadcn_component="radio"]::indicator:checked {{ background: {c["primary"]}; border-color: {c["primary"]}; }}

QCheckBox[qtshadcn_component="switch"] {{ spacing: 8px; }}
QCheckBox[qtshadcn_component="switch"]::indicator {{
  width: 32px; height: 18px; border-radius: 9px; background: {c["input"]}; border: 1px solid {c["input"]};
}}
QCheckBox[qtshadcn_component="switch"]::indicator:checked {{ background: {c["primary"]}; border-color: {c["primary"]}; }}

QComboBox[qtshadcn_component="select"] {{
  background: {c["background"]}; color: {c["foreground"]}; border: 1px solid {c["input"]};
  border-radius: {r_sm}; padding: 6px 10px; min-height: 20px;
}}
QComboBox[qtshadcn_component="select"]:focus {{ border-color: {c["ring"]}; }}
QComboBox[qtshadcn_component="select"] QAbstractItemView {{
  background: {c["popover"]}; color: {c["popoverForeground"]};
  border: 1px solid {c["border"]}; selection-background-color: {c["accent"]};
  selection-color: {c["accentForeground"]};
}}

QProgressBar[qtshadcn_component="progress"] {{
  background: {c["secondary"]}; border: none; border-radius: {r_lg}; text-align: center; min-height: 8px;
}}
QProgressBar[qtshadcn_component="progress"]::chunk {{ background: {c["primary"]}; border-radius: {r_lg}; }}
QSlider[qtshadcn_component="slider"]::groove:horizontal {{ height: 4px; background: {c["secondary"]}; border-radius: 2px; }}
QSlider[qtshadcn_component="slider"]::handle:horizontal {{
  width: 14px; margin: -6px 0; background: {c["background"]}; border: 2px solid {c["primary"]}; border-radius: 8px;
}}

QTabWidget[qtshadcn_component="tabs"]::pane {{ border: 1px solid {c["border"]}; border-radius: {r_md}; top: -1px; }}
{tab_bar}::tab {{ background: transparent; color: {c["mutedForeground"]}; padding: 7px 12px; border-bottom: 2px solid transparent; }}
{tab_bar}::tab:selected {{ color: {c["foreground"]}; border-bottom-color: {c["primary"]}; }}
{tab_bar}::tab:hover {{ color: {c["foreground"]}; background: {c["accent"]}; }}

QFrame[qtshadcn_component="separator"] {{ background: {c["border"]}; border: none; }}
{menu_rules}
"""


__all__ = ["render_stylesheet"]
